function translateInstructionWords(value: string) {
  return value.replace(/\b[a-z]+\b/gi, (word) => {
    return instructionWords[word.toLowerCase()] ?? word;
  });
}

export function translateExerciseText(value: string) {
  let translated = value.trim();
  for (const [pattern, replacement] of instructionPhrases) {
    translated = translated.replace(pattern, replacement);
  }

  return translateInstructionWords(translated)
    .replace(/\s+([,.])/g, "$1")
    .replace(/\s{2,}/g, " ")
    .trim();
}
